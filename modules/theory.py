# 匯入 NumPy 套件
# 用於陣列、矩陣、數值計算
import numpy as np

# 從 math 模組匯入 comb 函式
# comb(n, x) = 組合數 C(n, x)
# 表示從 n 個中選 x 個的方法數
from math import comb


# =====================================================
# 二項分配 PMF（機率質量函數）
# =====================================================
def binomial_pmf(n, p):
    """
    回傳 Binomial(n, p) 在 x = 0,1,...,n 的 PMF

    Binomial(n,p) 表示：
        做 n 次獨立試驗
        每次成功機率為 p

    隨機變數 X = 成功次數

    要求：
        P(X=x), x=0~n
    """

    # -------------------------------------------------
    # np.arange(n + 1)
    #
    # 產生：
    # [0,1,2,...,n]
    #
    # 因為 arange 終點不包含自己
    # 所以要寫 n+1
    # -------------------------------------------------
    x_values = np.arange(n + 1)

    # -------------------------------------------------
    # 建立每個 x 對應的 PMF 值
    #
    # Binomial公式：
    #
    # P(X=x)= C(n,x) p^x (1-p)^(n-x)
    #
    # 使用 list comprehension
    # -------------------------------------------------
    pmf_values = np.array([

        # comb(n,x) = 組合數
        # p**x = p 的 x 次方
        # (1-p)**(n-x) = 失敗部分

        comb(n, x) * (p ** x) * ((1 - p) ** (n - x))

        # for x in x_values
        # 對每個 x 計算一次
        for x in x_values
    ])

    # 回傳 x 與對應機率
    return x_values, pmf_values


# =====================================================
# Multinomial 理論共變異數矩陣
# =====================================================
def theoretical_covariance_matrix(n, probabilities):
    """
    multinomial 的理論 covariance matrix

    參數：
        n:
            總試驗次數

        probabilities:
            各類別機率
            例如 [0.2,0.5,0.3]

    回傳：
        k x k 共變異數矩陣
    """

    # -------------------------------------------------
    # 轉成 NumPy 陣列
    #
    # dtype=float 表示強制變成浮點數
    # -------------------------------------------------
    probabilities = np.asarray(probabilities, dtype=float)

    # -------------------------------------------------
    # 類別數量
    # 若 probabilities = [0.2,0.5,0.3]
    # 則 k = 3
    # -------------------------------------------------
    k = len(probabilities)

    # -------------------------------------------------
    # 建立 k x k 全零矩陣
    #
    # 例如 k=3:
    # [[0,0,0],
    #  [0,0,0],
    #  [0,0,0]]
    # -------------------------------------------------
    cov_matrix = np.zeros((k, k))

    # -------------------------------------------------
    # 雙層迴圈填入矩陣
    #
    # i = 列
    # j = 欄
    # -------------------------------------------------
    for i in range(k):
        for j in range(k):

            # -----------------------------------------
            # 對角線位置（自己與自己）
            #
            # Var(Xi)= n*pi*(1-pi)
            # -----------------------------------------
            if i == j:
                cov_matrix[i, j] = (
                    n *
                    probabilities[i] *
                    (1 - probabilities[i])
                )

            # -----------------------------------------
            # 非對角線位置
            #
            # Cov(Xi,Xj)= -n*pi*pj
            #
            # -----------------------------------------
            else:
                cov_matrix[i, j] = (
                    -n *
                    probabilities[i] *
                    probabilities[j]
                )

    return cov_matrix